#!/usr/bin/env node
/**
 * `npm run lint` entry point: runs ESLint over src and ../src and ratchets warnings.
 *
 * Most rules in eslint.config.mjs are `warn` (complexity, unused vars, no-explicit-any, ...)
 * so that legacy code does not block the build. Warnings never fail ESLint on their own, so
 * without a gate they only ever grow. This script fails when:
 *   - ESLint reports any error-level problem, or
 *   - a (rule, file) warning count rises above lint-baseline.json, or a rule/file pair
 *     appears that is not in the baseline.
 *
 * Counts are tracked per rule and per file, so one rule improving cannot hide another
 * getting worse. Counts may shrink freely; run `pnpm run lint:baseline:update` after
 * paying warnings down so the ratchet tightens.
 *
 * Same shape as check-hardcoded-strings.mjs / check-bare-tolocale.mjs.
 *
 * Usage:
 *   node scripts/check-lint-baseline.mjs                  # lint + check (CI)
 *   node scripts/check-lint-baseline.mjs --update-baseline
 */
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const extRoot = path.resolve(scriptDir, '..');
const repoRoot = path.resolve(extRoot, '..');
const baselinePath = path.join(extRoot, 'lint-baseline.json');
const require = createRequire(import.meta.url);

function runEslint(updating) {
	const out = path.join(os.tmpdir(), `eslint-${process.pid}.json`);
	const bin = path.join(path.dirname(require.resolve('eslint', { paths: [extRoot] })), '..', 'bin', 'eslint.js');
	const res = spawnSync(process.execPath, [bin, 'src', '../src', '--format', 'json', '--output-file', out,
		// When regenerating, treat `any` as a warning everywhere so the baseline records the files
		// that still contain it (the config makes it an error for files outside that list).
		...(updating ? ['--rule', '{"@typescript-eslint/no-explicit-any":"warn"}'] : [])], {
		cwd: extRoot,
		stdio: ['ignore', 'inherit', 'inherit'],
	});
	if (!fs.existsSync(out)) {
		console.error('❌ ESLint did not produce a report (exit ' + res.status + ').');
		process.exit(2);
	}
	try {
		return JSON.parse(fs.readFileSync(out, 'utf8'));
	} finally {
		fs.rmSync(out, { force: true });
	}
}

/** @returns {{ errors: string[], counts: Record<string, Record<string, number>> }} */
export function summarise(results) {
	const errors = [];
	const counts = {};
	for (const file of results) {
		const rel = path.relative(repoRoot, file.filePath).split(path.sep).join('/');
		for (const m of file.messages) {
			if (m.severity === 2) {
				errors.push(`${rel}:${m.line}:${m.column} ${m.ruleId ?? 'parse'} ${m.message}`);
			} else {
				const rule = m.ruleId ?? 'unknown';
				counts[rule] ??= {};
				counts[rule][rel] = (counts[rule][rel] ?? 0) + 1;
			}
		}
	}
	return { errors, counts };
}

function sortObject(o) {
	return Object.fromEntries(Object.keys(o).sort().map(k => [k, o[k]]));
}

export function findRegressions(counts, baseline) {
	const out = [];
	for (const [rule, files] of Object.entries(counts)) {
		for (const [file, n] of Object.entries(files)) {
			const allowed = baseline[rule]?.[file] ?? 0;
			if (n > allowed) { out.push(`${rule}  ${file}: ${n} (baseline ${allowed})`); }
		}
	}
	return out;
}

function main() {
	const { errors, counts } = summarise(runEslint(process.argv.includes('--update-baseline')));
	const total = Object.values(counts).reduce((a, f) => a + Object.values(f).reduce((x, y) => x + y, 0), 0);

	if (errors.length) {
		console.error(`❌ ESLint reported ${errors.length} error(s):\n  ${errors.slice(0, 50).join('\n  ')}`);
		if (errors.length > 50) { console.error(`  ... and ${errors.length - 50} more`); }
		process.exit(1);
	}

	if (process.argv.includes('--update-baseline')) {
		const rules = Object.fromEntries(Object.keys(counts).sort().map(r => [r, sortObject(counts[r])]));
		const payload = {
			'//': 'Generated by check-lint-baseline.mjs --update-baseline. Per-rule, per-file ESLint warning counts may shrink, never grow.',
			rules,
		};
		fs.writeFileSync(baselinePath, `${JSON.stringify(payload, null, '\t')}\n`);
		console.log(`✅ Lint baseline updated: ${total} warning(s) across ${Object.keys(rules).length} rule(s).`);
		return;
	}

	const baseline = fs.existsSync(baselinePath) ? JSON.parse(fs.readFileSync(baselinePath, 'utf8')).rules ?? {} : {};
	const regressions = findRegressions(counts, baseline);
	if (regressions.length) {
		console.error(`❌ ESLint warnings increased beyond lint-baseline.json:\n  ${regressions.join('\n  ')}`);
		console.error('\nFix the new warnings. If you paid warnings down elsewhere, run `pnpm run lint:baseline:update`.');
		process.exit(1);
	}

	let baselineTotal = 0;
	for (const files of Object.values(baseline)) { for (const n of Object.values(files)) { baselineTotal += n; } }
	console.log(`✅ ESLint: 0 errors, ${total} warning(s) (baseline ${baselineTotal}).`);
	if (total < baselineTotal) {
		console.log('   Warnings dropped — run `pnpm run lint:baseline:update` to lock in the improvement.');
	}
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) { main(); }
