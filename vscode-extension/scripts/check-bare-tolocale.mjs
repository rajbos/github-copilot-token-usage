#!/usr/bin/env node
/**
 * Ratchet for `toLocaleString()` / `toLocaleDateString()` / `toLocaleTimeString()`
 * called with no locale argument.
 *
 * A bare call formats with whatever locale the runtime defaults to, which in a
 * webview is the Electron host's — not the locale the user configured and not
 * the one `setFormatLocale()` was given. The result is a panel that mixes
 * `1,234.56` and `1.234,56` depending on which helper produced the number.
 *
 * The fix per call site depends on the receiver, which is why this ratchets
 * rather than auto-fixing:
 *   - a number → `formatNumber(x)` from `webview/shared/formatUtils`, which is
 *     exactly `x.toLocaleString(currentLocale)`
 *   - a Date → `formatAbsoluteDate(d)`, or pass the locale explicitly
 * `Date.prototype.toLocaleString()` and `Number.prototype.toLocaleString()`
 * produce completely different output, so a blind textual swap would be a bug.
 *
 * Counts are tracked per file: a file may shrink freely, but may not grow, and
 * a new file may not appear. Same shape as the hardcoded-strings ratchet.
 *
 * Usage:
 *   node scripts/check-bare-tolocale.mjs                  # check (CI)
 *   node scripts/check-bare-tolocale.mjs --update-baseline
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const extRoot = path.resolve(scriptDir, '..');
const repoRoot = path.resolve(extRoot, '..');
const baselinePath = path.join(scriptDir, 'bare-tolocale-baseline.json');

/** Trees whose output a user reads in a locale-sensitive way. */
const SCAN_ROOTS = [
	path.join(extRoot, 'src', 'webview'),
	path.join(repoRoot, 'cli', 'src'),
];

const BARE_CALL = /\.toLocale(?:String|DateString|TimeString)\(\s*\)/g;

function collectFiles(dir) {
	if (!fs.existsSync(dir)) { return []; }
	const out = [];
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) { out.push(...collectFiles(full)); continue; }
		if (entry.name.endsWith('.ts') && !entry.name.endsWith('.test.ts')) { out.push(full); }
	}
	return out;
}

export function countBareCalls() {
	const counts = {};
	for (const root of SCAN_ROOTS) {
		for (const file of collectFiles(root)) {
			const text = fs.readFileSync(file, 'utf8');
			const hits = text.match(BARE_CALL);
			if (!hits) { continue; }
			counts[path.relative(repoRoot, file).split(path.sep).join('/')] = hits.length;
		}
	}
	return counts;
}

function main() {
	const counts = countBareCalls();
	const total = Object.values(counts).reduce((a, b) => a + b, 0);

	if (process.argv.includes('--update-baseline')) {
		const payload = {
			'//': 'Generated by check-bare-tolocale.mjs --update-baseline. Counts may shrink, never grow.',
			counts,
		};
		fs.writeFileSync(baselinePath, `${JSON.stringify(payload, null, 2)}\n`);
		console.log(`✅ Baseline updated: ${total} bare toLocale*() call(s) across ${Object.keys(counts).length} file(s).\n`);
		return;
	}

	const baseline = fs.existsSync(baselinePath)
		? JSON.parse(fs.readFileSync(baselinePath, 'utf8')).counts
		: {};

	const regressions = [];
	for (const [file, count] of Object.entries(counts)) {
		const allowed = baseline[file] ?? 0;
		if (count > allowed) { regressions.push(`${file}: ${count} (baseline ${allowed})`); }
	}

	const baselineTotal = Object.values(baseline).reduce((a, b) => a + b, 0);
	console.log(`🔍 Bare toLocale*() calls: ${total} (baseline ${baselineTotal}).`);
	if (total < baselineTotal) {
		console.log(`ℹ️  ${baselineTotal - total} fewer than the baseline — run with --update-baseline to lock the improvement in.`);
	}

	if (regressions.length > 0) {
		console.error('\n❌ New bare toLocale*() call(s) — pass an explicit locale, or use');
		console.error('   formatNumber()/formatAbsoluteDate() from webview/shared/formatUtils:\n');
		for (const line of regressions) { console.error(`   - ${line}`); }
		console.error('');
		process.exit(1);
	}
	console.log('✅ No new bare toLocale*() calls.\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) { main(); }
